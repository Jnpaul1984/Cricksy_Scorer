<script setup lang="ts">
import { onMounted, reactive, ref, watch } from 'vue';

import { useSchoolContext } from '@/composables/useSchoolContext';
import { getErrorMessage } from '@/services/api';
import {
  createSchoolPlayer,
  deactivateSchoolPlayer,
  listSchoolPlayers,
  updateSchoolPlayer,
} from '@/services/schoolAdminApi';
import type { SchoolRosterPlayer } from '@/types/schoolAdmin';

type SchoolRosterPlayerCreatePayload = Parameters<typeof createSchoolPlayer>[1];
type SchoolRosterPlayerUpdatePayload = Parameters<typeof updateSchoolPlayer>[2];

const { organizationId, terminology, canManageRosterMetadata, canManageRosterLifecycle } =
  useSchoolContext();
const players = ref<SchoolRosterPlayer[]>([]);
const filter = ref<'active' | 'inactive' | 'all'>('active');
const loading = ref(true);
const saving = ref(false);
const error = ref('');
const success = ref('');
const editing = ref<SchoolRosterPlayer | null>(null);
const createForm = reactive({ player_name: '', student_identifier: '', year_group: '' });
const editForm = reactive({ student_identifier: '', year_group: '' });

async function load() {
  loading.value = true;
  error.value = '';
  try {
    players.value = await listSchoolPlayers(organizationId.value, filter.value);
  } catch (reason) {
    error.value = getErrorMessage(reason);
  } finally {
    loading.value = false;
  }
}
async function create() {
  saving.value = true;
  error.value = '';
  success.value = '';
  try {
    // Name is the only required input. Optional details are sent only when entered;
    // roster membership and canonical player IDs are always generated by the server.
    const payload: SchoolRosterPlayerCreatePayload = { player_name: createForm.player_name };
    if (createForm.year_group) payload.year_group = createForm.year_group;
    if (createForm.student_identifier) payload.student_identifier = createForm.student_identifier;
    await createSchoolPlayer(organizationId.value, payload);
    Object.assign(createForm, { player_name: '', student_identifier: '', year_group: '' });
    success.value = `Player added to the ${terminology.value.kindLabel} master roster.`;
    await load();
  } catch (reason) {
    error.value = getErrorMessage(reason);
  } finally {
    saving.value = false;
  }
}
function beginEdit(player: SchoolRosterPlayer) {
  editing.value = player;
  Object.assign(editForm, {
    student_identifier: player.student_identifier || '',
    year_group: player.year_group || '',
  });
}
async function saveMetadata() {
  if (!editing.value) return;
  // Send only fields the coach actually changed so untouched legacy values are never rewritten.
  const original = editing.value;
  const changes: SchoolRosterPlayerUpdatePayload = {};
  if (editForm.year_group !== (original.year_group || '')) {
    changes.year_group = editForm.year_group || null;
  }
  if (editForm.student_identifier !== (original.student_identifier || '')) {
    changes.student_identifier = editForm.student_identifier || null;
  }
  if (!Object.keys(changes).length) {
    editing.value = null;
    return;
  }
  saving.value = true;
  error.value = '';
  success.value = '';
  try {
    await updateSchoolPlayer(organizationId.value, original.id, changes);
    editing.value = null;
    success.value = `${terminology.value.kindLabel}-local player details updated.`;
    await load();
  } catch (reason) {
    error.value = getErrorMessage(reason);
  } finally {
    saving.value = false;
  }
}
async function setLifecycle(player: SchoolRosterPlayer, status: 'active' | 'inactive') {
  error.value = '';
  success.value = '';
  try {
    if (status === 'inactive') await deactivateSchoolPlayer(organizationId.value, player.id);
    else await updateSchoolPlayer(organizationId.value, player.id, { status: 'active' });
    success.value =
      status === 'active' ? 'Roster membership reactivated.' : 'Roster membership deactivated.';
    await load();
  } catch (reason) {
    error.value = getErrorMessage(reason);
  }
}

watch(filter, load);
onMounted(load);
</script>

<template>
  <section class="panel" aria-labelledby="players-heading">
    <header>
      <p class="eyebrow">Reusable player identities</p>
      <h2 id="players-heading">{{ terminology.kindLabel }} master roster</h2>
      <p>
        Add players by name. Cricksy assigns player IDs automatically, players do not need a
        Cricksy login, and they can be reused across multiple teams. Captain and wicketkeeper are
        chosen for each match during match setup.
      </p>
    </header>
    <div v-if="error" class="notice error" role="alert">{{ error }}</div>
    <div v-if="success" class="notice success" role="status">{{ success }}</div>
    <form v-if="canManageRosterMetadata" class="editor" @submit.prevent="create">
      <h3>Add player</h3>
      <label
        >Player name <input v-model.trim="createForm.player_name" required maxlength="255"
      /></label>
      <button type="submit" :disabled="saving" :aria-busy="saving">Add to roster</button>
      <details class="optional-details" data-test="add-player-optional-details">
        <summary>Optional details</summary>
        <div class="optional-fields">
          <label>Group <input v-model.trim="createForm.year_group" maxlength="64" /></label>
          <label
            >External reference
            <input
              v-model.trim="createForm.student_identifier"
              maxlength="128"
              aria-describedby="create-external-reference-help"
            />
            <small id="create-external-reference-help" class="hint"
              >Optional reference from another system, such as a register number. It is not
              required, need not be unique and is never used to identify players.</small
            ></label
          >
        </div>
      </details>
    </form>
    <div class="toolbar">
      <label
        >Roster status
        <select v-model="filter">
          <option value="active">Active</option>
          <option value="inactive">Inactive</option>
          <option value="all">All retained records</option>
        </select></label
      >
    </div>
    <p v-if="loading" role="status">Loading master roster…</p>
    <div v-else-if="!players.length" class="notice">No players match this status.</div>
    <div v-else class="table-wrap">
      <table>
        <thead>
          <tr>
            <th>Player</th>
            <th>Group</th>
            <th>Status</th>
            <th>Actions</th>
          </tr>
        </thead>
        <tbody>
          <tr v-for="player in players" :key="player.id">
            <td>
              {{ player.player_name }}
              <small v-if="player.student_identifier" class="reference"
                >Ref: {{ player.student_identifier }}</small
              >
            </td>
            <td>{{ player.year_group || '—' }}</td>
            <td>
              <span class="status">{{ player.status }}</span>
            </td>
            <td>
              <div class="button-row">
                <button
                  v-if="canManageRosterMetadata"
                  type="button"
                  class="compact secondary"
                  @click="beginEdit(player)"
                >
                  Edit metadata
                </button>
                <button
                  v-if="canManageRosterLifecycle && player.status === 'active'"
                  type="button"
                  class="compact danger"
                  @click="setLifecycle(player, 'inactive')"
                >
                  Deactivate
                </button>
                <button
                  v-if="canManageRosterLifecycle && player.status === 'inactive'"
                  type="button"
                  class="compact"
                  @click="setLifecycle(player, 'active')"
                >
                  Reactivate
                </button>
              </div>
            </td>
          </tr>
        </tbody>
      </table>
    </div>
    <dialog :open="Boolean(editing)" aria-labelledby="edit-player-title">
      <form v-if="editing" method="dialog" @submit.prevent="saveMetadata">
        <h3 id="edit-player-title">Edit {{ editing.player_name }}</h3>
        <label>Group <input v-model.trim="editForm.year_group" maxlength="64" /></label>
        <label
          >External reference (optional)
          <input
            v-model.trim="editForm.student_identifier"
            maxlength="128"
            aria-describedby="edit-external-reference-help"
          />
          <small id="edit-external-reference-help" class="hint"
            >Reference from another system or an earlier local player ID. Need not be unique and is
            never used to identify players.</small
          ></label
        >
        <details class="support-details" data-test="player-support-details">
          <summary>Support details</summary>
          <p class="hint">Generated automatically. These IDs are read-only.</p>
          <dl>
            <dt>Roster membership ID</dt>
            <dd>
              <code>{{ editing.id }}</code>
            </dd>
            <dt>Player profile ID</dt>
            <dd>
              <code>{{ editing.player_profile_id }}</code>
            </dd>
          </dl>
        </details>
        <div class="button-row">
          <button type="submit" :disabled="saving">Save</button
          ><button type="button" class="secondary" @click="editing = null">Cancel</button>
        </div>
      </form>
    </dialog>
  </section>
</template>

